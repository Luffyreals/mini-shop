package com.minishop.desktop;

import com.minishop.support.TestImages;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.Arrays;
import java.util.Base64;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatNoException;
import static org.junit.jupiter.api.Assertions.assertTimeoutPreemptively;

/**
 * {@link WebpDecoder} decodes real WebP bytes through {@code javax.imageio} (QĐ7 of the D3 plan) and treats the file as
 * untrusted: nothing throws, and a header that claims a huge size is refused before any pixel is allocated. No JavaFX
 * toolkit: the decoder is plain Java.
 *
 * <p><b>Fixtures</b> (generated by us, no licence row needed; written to a {@link TempDir} by each test):
 * <ul>
 *   <li>{@code LOSSLESS_1X1}: the well-known WebP feature-test image used by Modernizr and Google (a 1x1 lossless
 *       image).</li>
 *   <li>{@code ALPHA_2X2}: a 2x2 lossless image made with ffmpeg; its first pixel is red at about 50% alpha.</li>
 *   <li>{@code HUGE_HEADER}: a tiny file whose VP8L header claims 16383 x 16383 pixels, with no pixel data.</li>
 *   <li>{@code desktop/webp/large600.webp} (test resource, 1022 bytes): a 600 x 400 lossy image made with ffmpeg
 *       from a synthetic gradient.</li>
 * </ul>
 */
class WebpDecoderTest {

    private static final String LOSSLESS_1X1 = "UklGRhoAAABXRUJQVlA4TA0AAAAvAAAAEAcQERGIiP4HAA==";
    private static final String ALPHA_2X2 = "UklGRhwAAABXRUJQVlA4TA8AAAAvAUAAEAcQ/Y/+BSKi/wEA";
    private static final String HUGE_HEADER = "UklGRhIAAABXRUJQVlA4TAUAAAAv/r//DwA=";

    @TempDir
    Path dir;

    private final WebpDecoder decoder = new WebpDecoder();

    private Path write(String name, byte[] bytes) throws IOException {
        Path file = dir.resolve(name);
        Files.write(file, bytes);
        return file;
    }

    private Path writeBase64(String name, String base64) throws IOException {
        return write(name, Base64.getDecoder().decode(base64));
    }

    private Path large600() throws IOException {
        try (InputStream in = WebpDecoderTest.class.getResourceAsStream("/desktop/webp/large600.webp")) {
            assertThat(in).as("test resource large600.webp").isNotNull();
            Path file = dir.resolve("large600.webp");
            Files.write(file, in.readAllBytes());
            return file;
        }
    }

    // ------------------------------------------------------------------ small real images

    @Test
    void decode_aLossless1x1Image_returnsItsSize() throws IOException {
        Path file = writeBase64("one.webp", LOSSLESS_1X1);

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 100, 100);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(1);
        assertThat(image.get().height()).isEqualTo(1);
        assertThat(image.get().argb()).hasSize(1);
    }

    @Test
    void decode_anImageWithAlpha_keepsTheAlphaAndColour() throws IOException {
        Path file = writeBase64("alpha.webp", ALPHA_2X2);

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 100, 100);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(2);
        assertThat(image.get().height()).isEqualTo(2);
        assertThat(image.get().argb()).hasSize(4);
        assertThat(image.get().argb()[0]).isEqualTo(0x7FFF0000);
    }

    @Test
    void decode_withNoBox_keepsTheOriginalSizeOfASmallImage() throws IOException {
        Path file = writeBase64("alpha.webp", ALPHA_2X2);

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 0, 0);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(2);
    }

    // ------------------------------------------------------------------ a larger image, scaled to the box

    @Test
    void decode_aLargeImageIntoASmallBox_isShrunkToTwiceTheBoxKeepingTheRatio() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 100, 100);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(200);
        assertThat(image.get().height()).isEqualTo(133);
        assertThat(image.get().argb()).hasSize(200 * 133);
    }

    @Test
    void decode_withBoxZero_keepsTheFullSize() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 0, 0);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(600);
        assertThat(image.get().height()).isEqualTo(400);
        assertThat(image.get().argb()).hasSize(600 * 400);
    }

    @Test
    void decode_aBoxLargerThanTheImage_doesNotEnlargeIt() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 2000, 2000);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(600);
        assertThat(image.get().height()).isEqualTo(400);
    }

    @Test
    void decode_withOnlyOneBoxSideGiven_limitsByThatSide() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 100, 0);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(200);
        // 133 or 134, depending on how the subsampled reader rounds the height
        assertThat(image.get().height()).isBetween(133, 134);
    }

    @Test
    void decode_coverMode_coversTheBoxAndIsCappedAtTwiceTheBox() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 100, 100, true);

        assertThat(image).isPresent();
        int width = image.get().width();
        int height = image.get().height();
        // the shorter side covers the box (here 2 x 100 for crisp screens), the other side keeps the 3:2 ratio
        assertThat(Math.min(width, height)).isGreaterThanOrEqualTo(100).isLessThanOrEqualTo(2 * 100);
        assertThat(Math.max(width, height)).isLessThan(600);
        assertThat((double) width / height).isBetween(1.45, 1.55);
        assertThat(image.get().argb()).hasSize(width * height);
    }

    @Test
    void decode_coverMode_isLargerThanFitMode() throws IOException {
        Path file = large600();

        WebpDecoder.DecodedImage fit = decoder.decode(file, 100, 100, false).orElseThrow();
        WebpDecoder.DecodedImage cover = decoder.decode(file, 100, 100, true).orElseThrow();

        assertThat(cover.height()).isGreaterThan(fit.height());
        assertThat(cover.width()).isGreaterThanOrEqualTo(fit.width());
    }

    @Test
    void decode_coverMode_withABoxLargerThanTheImage_doesNotEnlarge() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 2000, 2000, true);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(600);
        assertThat(image.get().height()).isEqualTo(400);
    }

    @Test
    void decode_coverMode_withNoBox_keepsTheFullSize() throws IOException {
        Path file = large600();

        Optional<WebpDecoder.DecodedImage> image = decoder.decode(file, 0, 0, true);

        assertThat(image).isPresent();
        assertThat(image.get().width()).isEqualTo(600);
        assertThat(image.get().height()).isEqualTo(400);
    }

    // ------------------------------------------------------------------ untrusted files

    @Test
    void decode_aHeaderClaiming16383x16383_isRefusedQuicklyWithoutDecoding() throws IOException {
        Path file = writeBase64("huge.webp", HUGE_HEADER);

        Optional<WebpDecoder.DecodedImage> image = assertTimeoutPreemptively(Duration.ofSeconds(10),
                () -> decoder.decode(file, 100, 100));

        assertThat(image).isEmpty();
    }

    @Test
    void maxPixels_isBelowTheClaimedSizeOfTheHugeHeader() {
        assertThat((long) 16383 * 16383).isGreaterThan(WebpDecoder.MAX_PIXELS);
    }

    @Test
    void decode_aFileWithOnlyTheMagicBytes_returnsEmpty() throws IOException {
        Path file = write("magic.webp", TestImages.webp(40));

        assertThat(decoder.decode(file, 100, 100)).isEmpty();
    }

    @Test
    void decode_aMissingFile_returnsEmpty() {
        assertThat(decoder.decode(dir.resolve("missing.webp"), 100, 100)).isEmpty();
    }

    @Test
    void decode_aNullPath_returnsEmptyInsteadOfThrowing() {
        assertThat(decoder.decode(null, 100, 100)).isEmpty();
    }

    @Test
    void decode_anEmptyFile_returnsEmpty() throws IOException {
        Path file = write("empty.webp", new byte[0]);

        assertThat(decoder.decode(file, 100, 100)).isEmpty();
    }

    @Test
    void decode_aDirectory_returnsEmpty() {
        assertThat(decoder.decode(dir, 100, 100)).isEmpty();
    }

    @Test
    void decode_aJpegNamedWebp_returnsEmpty() throws IOException {
        Path file = write("fake.webp", TestImages.jpeg(200));

        assertThat(decoder.decode(file, 100, 100)).isEmpty();
    }

    @Test
    void decode_aTruncatedRealImage_neverThrows() throws IOException {
        byte[] full = Files.readAllBytes(large600());
        Path file = write("cut.webp", Arrays.copyOf(full, full.length / 2));

        assertThatNoException().isThrownBy(() -> decoder.decode(file, 100, 100));
    }

    @Test
    void decode_aCorruptedBodyOfARealImage_neverThrows() throws IOException {
        byte[] bytes = Files.readAllBytes(large600());
        for (int i = 40; i < bytes.length; i += 7) {
            bytes[i] = (byte) 0xFF;
        }
        Path file = write("corrupt.webp", bytes);

        assertThatNoException().isThrownBy(() -> decoder.decode(file, 100, 100));
    }

    // ------------------------------------------------------------------ subsampling

    @Test
    void subsampling_ofALargeImage_isTheLargestStepThatKeepsTwiceTheBox() {
        assertThat(WebpDecoder.subsampling(4000, 3000, 200, 200)).isEqualTo(7);
    }

    @Test
    void subsampling_withNoBox_isOne() {
        assertThat(WebpDecoder.subsampling(100, 100, 0, 0)).isEqualTo(1);
    }

    @Test
    void subsampling_ofASmallImage_isOne() {
        assertThat(WebpDecoder.subsampling(100, 100, 200, 200)).isEqualTo(1);
        assertThat(WebpDecoder.subsampling(1, 1, 1, 1)).isEqualTo(1);
    }

    @Test
    void subsampling_usesTheSideThatAllowsTheSmallerStep() {
        // width allows 4000 / (2 * 100) = 20, height allows 300 / (2 * 100) = 1
        assertThat(WebpDecoder.subsampling(4000, 300, 100, 100)).isEqualTo(1);
    }

    @Test
    void subsampling_withOnlyOneBoxSide_usesThatSide() {
        assertThat(WebpDecoder.subsampling(600, 400, 100, 0)).isEqualTo(3);
        assertThat(WebpDecoder.subsampling(600, 400, 0, 100)).isEqualTo(2);
    }
}
