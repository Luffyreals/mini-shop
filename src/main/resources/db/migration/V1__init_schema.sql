-- V1: initial schema (spec 001, section 7). Portable between PostgreSQL and H2 (PostgreSQL mode):
-- varchar instead of text, numeric(12,0) for VND, plain CHECK constraints instead of enum types.

create table users (
    id            bigint generated by default as identity,
    email         varchar(255) not null,
    password_hash varchar(100) not null,
    full_name     varchar(100) not null,
    phone         varchar(20),
    role          varchar(20)  not null,
    created_at    timestamp with time zone not null default current_timestamp,
    constraint pk_users primary key (id),
    constraint uq_users_email unique (email),
    constraint ck_users_role check (role in ('USER', 'ADMIN'))
);

create table categories (
    id          bigint generated by default as identity,
    name        varchar(100) not null,
    description varchar(1000),
    constraint pk_categories primary key (id),
    constraint uq_categories_name unique (name)
);

create table products (
    id          bigint generated by default as identity,
    category_id bigint        not null,
    name        varchar(200)  not null,
    description varchar(4000),
    price       numeric(12,0) not null,
    stock       integer       not null,
    image_path  varchar(255),
    active      boolean       not null default true,
    created_at  timestamp with time zone not null default current_timestamp,
    updated_at  timestamp with time zone not null default current_timestamp,
    constraint pk_products primary key (id),
    constraint fk_products_category foreign key (category_id) references categories (id),
    constraint ck_products_price_non_negative check (price >= 0),
    constraint ck_products_stock_non_negative check (stock >= 0)
);
create index idx_products_category_id on products (category_id);
create index idx_products_name on products (name);

create table carts (
    id         bigint generated by default as identity,
    user_id    bigint not null,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint pk_carts primary key (id),
    constraint uq_carts_user unique (user_id),
    constraint fk_carts_user foreign key (user_id) references users (id)
);

create table cart_items (
    id         bigint generated by default as identity,
    cart_id    bigint  not null,
    product_id bigint  not null,
    quantity   integer not null,
    constraint pk_cart_items primary key (id),
    constraint fk_cart_items_cart foreign key (cart_id) references carts (id),
    constraint fk_cart_items_product foreign key (product_id) references products (id),
    constraint uq_cart_items_cart_product unique (cart_id, product_id),
    constraint ck_cart_items_quantity_positive check (quantity > 0)
);
create index idx_cart_items_product_id on cart_items (product_id);

create table orders (
    id               bigint generated by default as identity,
    user_id          bigint        not null,
    status           varchar(20)   not null,
    receiver_name    varchar(100)  not null,
    phone            varchar(20)   not null,
    shipping_address varchar(500)  not null,
    note             varchar(500),
    payment_method   varchar(20)   not null,
    total_amount     numeric(12,0) not null,
    created_at       timestamp with time zone not null default current_timestamp,
    updated_at       timestamp with time zone not null default current_timestamp,
    constraint pk_orders primary key (id),
    constraint fk_orders_user foreign key (user_id) references users (id),
    constraint ck_orders_status check (status in ('PENDING', 'CONFIRMED', 'SHIPPING', 'DELIVERED', 'CANCELLED')),
    constraint ck_orders_payment_method check (payment_method in ('COD')),
    constraint ck_orders_total_non_negative check (total_amount >= 0)
);
create index idx_orders_user_id on orders (user_id);
create index idx_orders_status on orders (status);
create index idx_orders_created_at on orders (created_at);

create table order_items (
    id           bigint generated by default as identity,
    order_id     bigint        not null,
    product_id   bigint        not null,
    product_name varchar(200)  not null,
    unit_price   numeric(12,0) not null,
    quantity     integer       not null,
    constraint pk_order_items primary key (id),
    constraint fk_order_items_order foreign key (order_id) references orders (id),
    constraint fk_order_items_product foreign key (product_id) references products (id),
    constraint ck_order_items_unit_price_non_negative check (unit_price >= 0),
    constraint ck_order_items_quantity_positive check (quantity > 0)
);
create index idx_order_items_order_id on order_items (order_id);
create index idx_order_items_product_id on order_items (product_id);
